const dicts: Record<Lang, Dict> = { ckb, en };

const EASTERN = '٠١٢٣٤٥٦٧٨٩';
export function fmtNum(n: number | string, lang: Lang) {
  const s = String(n);
  return lang === 'ckb' ? s.replace(/\d/g, (d) => EASTERN[+d]) : s;
}

export function translate(lang: Lang, key: string, params?: Record<string, string | number>) {
  const d = dicts[lang] as Record<string, string>;
  let s = d[key] ?? (dicts.en as Record<string, string>)[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, typeof v === 'number' ? fmtNum(v, lang) : v);
  return s;
}

export function useT() {
  const lang = usePrefs((p) => p.lang);
  const t = (key: TKey | string, params?: Record<string, string | number>) => translate(lang, key, params);
  return Object.assign(t, { lang, n: (v: number | string) => fmtNum(v, lang) });
}
